import { useI18n } from './context.tsx'

/**
 * Пояснення хорватського юридичного терміна — поруч із самим терміном.
 *
 * Термін показується в кожній локалі, бо саме його людина побачить у
 * документах і почує від бухгалтера; переклад його не замінює, а супроводжує
 * (CONTEXT.md). Хорватською поруч стоїть коротке тлумачення, а не повтор.
 *
 * Термін, якого в словнику немає, лишається без пояснення, а не з порожнім
 * рядком під ним. Що жодна назва з рушія так не загубиться, стежить тест.
 */
export const Prijevod = ({ pojam }: { readonly pojam: string }) => {
  const { t } = useI18n()
  const prijevod = t.pojmovi[pojam]

  return prijevod === undefined ? null : <span className="prijevod">{prijevod}</span>
}
