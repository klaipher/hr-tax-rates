/**
 * Курс EUR/UAH на боці інтерфейсу: що взяти з поля, а що лишити ланцюжку.
 *
 * Сам ланцюжок — живий запит до НБУ → снепшот із датою → ручне значення —
 * живе в `resolveExchangeRate` і є єдиним вводом-виводом у проєкті. Тут
 * лежить лише те, що вирішує форма: чи людина вбила курс руками, і як
 * повернути гривні в євро тим самим числом, яким їх дістали.
 *
 * Окремим модулем, а не всередині компонента, з однієї причини: це чиста
 * арифметика й чиста перевірка вводу, і їх треба вміти спитати з тесту.
 */
import type { ExchangeRate, IsoDate, ManualExchangeRate } from '@hr-tax/data'
import { NBU_EUR_UAH_SNAPSHOT } from '@hr-tax/data'
import type { Money } from '@hr-tax/engine'
import { eur } from '@hr-tax/engine'

/**
 * Число рушія — воно завжди `Decimal`. Тип береться з контракту, а не з
 * `decimal.js` напряму: інтерфейс нічого не рахує сам і бібліотеки не тягне.
 */
type DecimalniBroj = ExchangeRate['value']

/** Те, що стоїть у полях курсу: саме число і дата, на яку воно дійсне. */
export interface RucniTecaj {
  /** Порожньо — курс бере ланцюжок. */
  readonly vrijednost: string
  /**
   * Дата, якій курс належить. Її задає людина, а не годинник: «курс 48,50»
   * без дати нічого не означає, і підставити сюди сьогодні означало б
   * приписати числу свіжість, якої воно не має.
   */
  readonly naDan: IsoDate
}

/**
 * Початковий стан полів.
 *
 * Поле числа порожнє навмисно: ручний курс обриває ланцюжок ще до запиту,
 * тож підставлене туди значення снепшоту не дало б живому курсу НБУ жодного
 * шансу. Дата ж наперед відома — це дата снепшоту, і людині зручніше правити
 * її, ніж набирати з нуля.
 */
export const pocetniRucniTecaj: RucniTecaj = {
  vrijednost: '',
  naDan: NBU_EUR_UAH_SNAPSHOT.asOf,
}

/**
 * Десятковий запис без знака й без коми — рівно те, що приймає `Decimal`
 * і що друкує НБУ.
 */
const DESETKOVI_BROJ = /^\d+(\.\d+)?$/

/**
 * Ручний курс для резолвера — або `undefined`, коли поле порожнє чи в ньому
 * не додатне число.
 *
 * Нечислове й недодатне значення тут не помилка, на яку треба лаятися, а
 * просто «ручного курсу немає»: людина посеред набору бачить `4`, `4.`, `48`
 * — і жоден із цих проміжних станів не привід підмінити курс НБУ нулем.
 *
 * Значення передається рядком, а не числом: `Decimal` розбере його сам і
 * без утрати знаків, тоді як прохід через `number` уже на цьому кроці з'їв
 * би точність, яку резолвер потім не відновить.
 */
export const rucniTecajZa = ({ vrijednost, naDan }: RucniTecaj): ManualExchangeRate | undefined => {
  const ocisceno = vrijednost.trim()
  if (!DESETKOVI_BROJ.test(ocisceno) || Number(ocisceno) <= 0) return undefined

  return { value: ocisceno, asOf: naDan }
}

/**
 * Гривні назад у євро за тим самим курсом, яким їх дістали.
 *
 * У `Decimal`, а не через `Number`: сума вже пройшла множення на курс, і
 * повертати її діленням у float означало б дописати до неї дрейф на рівному
 * місці.
 */
export const uEure = (iznos: DecimalniBroj, tecaj: ExchangeRate): Money<'EUR'> =>
  eur(iznos.dividedBy(tecaj.value))
