import type { LegalReference } from '@hr-tax/data'

/**
 * Цитата джерела одним рядком: `Zakon o doprinosima, čl. 70.`.
 *
 * Потрібна там, де посилання показує саму лише статтю: клікабельне `čl. 70.`
 * без назви акта нічого не означає для того, хто читає сторінку зчитувачем
 * екрана або відкриває список посилань окремо. Тому назва акта їде разом зі
 * статтею в доступну назву посилання.
 */
export const citat = (izvor: LegalReference): string => `${izvor.act}, ${izvor.article}`
