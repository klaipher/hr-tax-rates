import type { ReactNode } from 'react'

/**
 * Довге пояснення під згорткою.
 *
 * Пояснення в цьому калькуляторі не декоративні: майже кожне з них відповідає
 * на питання «чому число саме таке», і викинути їх означало б лишити цифру без
 * підстави. Але читають їх один раз, а бачать — щоразу, і абзац на сім рядків,
 * що стоїть розгорнутим завжди, витісняє з екрана те, заради чого людина
 * прийшла.
 *
 * Тому текст лишається слово в слово, а видимим стає рівно заголовок — і той
 * названий тим, на що пояснення відповідає, а не безликим «докладніше». Хто
 * питання не має, той його й не розгортає.
 */
export const Pojasnjenje = ({
  naslov,
  children,
}: {
  /** Питання, на яке відповідає текст усередині. */
  readonly naslov: string
  readonly children: ReactNode
}) => (
  <details className="pojasnjenje">
    <summary className="pojasnjenje__naslov">{naslov}</summary>
    <div className="pojasnjenje__tijelo">{children}</div>
  </details>
)
