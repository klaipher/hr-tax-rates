import type Decimal from 'decimal.js'
import type { CurrencyCode } from '../fx/currency.ts'
import type { LegalReference } from '../legal.ts'

/**
 * Країна, податки якої рахуються для порівняння з хорватськими режимами.
 *
 * Код за ISO 3166-1 alpha-2 і збігається з `jurisdiction` у посиланнях на
 * закон — інакше розбивка вела б на право іншої держави.
 */
export type HomeCountryCode = 'UA'

/**
 * Один рядок розбивки — окремий обов'язковий платіж.
 *
 * Прози тут немає навмисно: назву рядка підставляє UI за `id`, бо застосунок
 * тримає три локалі рівної повноти, а `packages/data` не місце для перекладів.
 */
export interface HomeCountryCharge {
  /** Стабільний ідентифікатор платежу. Ключ локалізації і опора тестів. */
  readonly id: string
  /** Річна сума у валюті результату. */
  readonly annual: Decimal
  /**
   * Усі акти, з яких складається це число, — і ставка, і величина, до якої
   * ставку застосовано (ADR-0002). Українському ЄСВ, наприклад, потрібні два:
   * ставка внеску і мінімальна зарплата.
   */
  readonly references: readonly LegalReference[]
}

/**
 * Порушена межа режиму: дохід виріс за ту, при якій режим ще застосовний.
 *
 * Порушення повідомляється, а не приховується мовчазним перерахунком: за
 * межею діють інші правила, і показати число, ніби нічого не сталося, —
 * гірше, ніж не показати нічого.
 */
export interface HomeCountryLimitBreach {
  /**
   * Ключ локалізації. На відміну від `id` платежу, який називає конкретний
   * український податок, межа тут описана структурно — «річний ліміт доходу»
   * є і в хорватського `paušalni obrt`, тож ключ спільний для всіх країн.
   */
  readonly id: string
  /** Межа у валюті результату. */
  readonly limit: Decimal
  /** На скільки межу перевищено. */
  readonly excess: Decimal
  /** Акти, що встановлюють межу. */
  readonly references: readonly LegalReference[]
}

/**
 * Результат розрахунку однієї країни.
 *
 * Форма навмисно та сама, що в хорватського `režim`: розбивка платежів,
 * сума на руки як головне число і ефективна ставка як вторинне. Саме на
 * однаковій формі тримається зіставність.
 */
export interface HomeCountryResult {
  readonly country: HomeCountryCode
  /**
   * Валюта всього результату — один раз на весь розрахунок, а не на кожній
   * сумі: усі платежі однієї країни за визначенням в одній валюті, тож жодне
   * число звідси не мандрує без оголошеної валюти. Перерахунок у євро за
   * курсом — справа рушія, де живе `Money<C>` з валютою в типі суми.
   */
  readonly currency: CurrencyCode
  readonly annualIncome: Decimal
  readonly charges: readonly HomeCountryCharge[]
  /** Сума всіх рядків розбивки за рік. */
  readonly totalCharges: Decimal
  /** Сума на руки за рік: дохід мінус платежі. Може бути від'ємною. */
  readonly net: Decimal
  /** Частка платежів у доході: 0,0828 — це 8,28%. */
  readonly effectiveRate: Decimal
  /** Порушені межі режиму. Порожній масив означає, що режим застосовний. */
  readonly breaches: readonly HomeCountryLimitBreach[]
}

/**
 * Модуль рідної країни.
 *
 * Інтерфейс мінімальний свідомо: країна бере річний дохід і повертає
 * розбивку. Додати країну — це новий файл даних і рядок у реєстрі; рушій при
 * цьому не змінюється.
 */
export interface HomeCountry {
  readonly code: HomeCountryCode
  /** Валюта, в якій країна рахує свої платежі. */
  readonly currency: CurrencyCode
  /** Річний дохід задається у валюті країни, за її власним визначенням доходу. */
  readonly calculate: (annualIncome: Decimal.Value) => HomeCountryResult
}
