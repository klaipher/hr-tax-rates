/**
 * Норми `PDV` (ПДВ / VAT), на яких стоїть розрахунок обрту однієї людини.
 *
 * Набір навмисно вузький і покриває рівно дві сторони, які відчуває обрт:
 *
 * - **вихідну** — чи несе рахунок хорватський `PDV`. Для послуг платникові
 *   податку місце надання за `čl. 17. st. 1.` переїжджає до отримувача, тож
 *   хорватського `PDV` на рахунку немає, а бізнес-клієнт у ЄС рахує податок
 *   собі сам — це і є `prijenos porezne obveze`;
 * - **вхідну** — послуги, куплені в постачальника з-за кордону. Їх отримувач
 *   нараховує собі сам (`čl. 75. st. 1. t. 6.`), і поза системою `PDV` не має
 *   права відняти нарахований податок як `pretporez` (`čl. 90.g`). У системі
 *   право з’являється (`čl. 58. st. 2.`) — на цьому й стоїть інверсія, заради
 *   якої модуль існує.
 *
 * **Свідомо не змодельовано** (реєстр — `PDV_IZVAN_OPSEGA`): OSS для продажів
 * споживачам ЄС, `prag stjecanja` для придбання товарів і `razmjerni odbitak`.
 * Кожна з цих тем — окремий режим із власними обов’язками, і жодна з них не
 * потрібна, щоб показати клин `PDV` у ціні та невідшкодовуваний `PDV` на
 * вході. Знижені ставки `čl. 38. st. 2. i st. 3.` теж не моделюються: вхідна
 * сторона рахується за загальною ставкою.
 *
 * Хто зобов’язаний увійти в систему `PDV` — вирішує поріг `čl. 90. st. 1.`.
 * Той самий поріг забирає `paušalni obrt`; недоступність режиму рахує
 * `engine/src/pausalni-obrt.ts`, і число тут не дублюється, а звіряється
 * тестом.
 */

const CHECKED_ON = '2026-08-04' as const

/** Стаття `Zakon o PDV-u` разом із датою звірки — форма, якої вимагає ADR-0002. */
const clanak = (article: string): LegalReference => ({
  ...ZAKON_O_PDV,
  article,
  checkedOn: CHECKED_ON,
})

