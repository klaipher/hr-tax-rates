/** Тема `PDV`, якої модуль свідомо не рахує, разом із нормою, що її вводить. */
export interface IzvanOpsega {
  /** Коротка назва теми — те, що видно на екрані. */
  readonly tema: string
  /** Чому не рахуємо і що це означає для людини. */
  readonly obrazlozenje: string
  /** Норма, яка тему вводить: щоб «не рахуємо» не звучало як «не існує». */
  readonly izvor: LegalReference
}

